import { randomBytes } from 'node:crypto';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createApp } from '../server.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const directory = await mkdtemp(join(tmpdir(), 'alter-ego-nutrition-browser-'));
const password = randomBytes(24).toString('hex');
let calls = 0;
let offline = false;
const server = createApp({ config: { password, origin: '', dataDir: directory }, fetchImpl: async url => {
  calls++;
  if (new URL(url).hostname !== 'world.openfoodfacts.org') throw new Error('Unexpected provider');
  if (offline) throw new Error('Simulated outage');
  const product = { code: '2000000000008', product_name: 'Produit test citron', brands: 'Marque fictive', nutriments: { 'energy-kcal_100g': 123.4 } };
  return new URL(url).pathname.includes('/product/') ? Response.json({ status: 'success', product }) : Response.json({ products: [product,
    { code: '2000000000015', product_name: 'Produit test incomplet', nutriments: {} }] });
} });
let browser;
try {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 360, height: 800 }, locale: 'fr-FR' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/calories');
  await page.locator('#password:not([disabled])').waitFor();
  await page.locator('#password').fill(password); await page.locator('#login-submit').click();
  await page.locator('#journal:not([hidden])').waitFor();
  await page.locator('#add-food').click();
  await page.locator('#food-query').fill('citron');
  await page.locator('#search-food').click();
  await page.getByRole('button', { name: 'Choisir Produit test citron', exact: true }).waitFor();
  if (!await page.getByRole('button', { name: 'Choisir Produit test incomplet', exact: true }).isDisabled()) throw new Error('Missing energy is selectable');
  await page.getByRole('button', { name: 'Choisir Produit test citron', exact: true }).click();
  await page.locator('#portion-quantity').fill('125');
  if (await page.locator('#food-kcal').inputValue() !== '') throw new Error('Unit assumed without confirmation');
  await page.locator('#portion-unit').selectOption('g');
  if (await page.locator('#food-kcal').inputValue() !== '154.3') throw new Error('Incorrect portion calculation');
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('#food-dialog').scrollWidth > document.querySelector('#food-dialog').clientWidth)) throw new Error('Mobile form overflows');
  await mkdir(join(root, 'artifacts'), { recursive: true });
  await page.screenshot({ path: join(root, 'artifacts/nutrition-mobile.png'), fullPage: true });
  await page.locator('#save-food').click(); await page.locator('#food-dialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.getElementById('total').textContent === '154,3');
  await page.locator('.entry-source').waitFor();
  const source = await page.locator('.entry-source').getAttribute('href');
  if (source !== 'https://world.openfoodfacts.org/product/2000000000008') throw new Error('Source not preserved');
  await page.reload(); await page.locator('.entry-source').waitFor();
  await page.getByRole('button', { name: 'Modifier Produit test citron', exact: true }).click();
  await page.locator('#food-meal').selectOption('dinner'); await page.locator('#save-food').click();
  await page.locator('#food-dialog').waitFor({ state: 'hidden' }); await page.locator('.entry-source').waitFor();
  await page.locator('#add-food').click();
  await page.locator('#local-search').check(); await page.locator('#food-query').fill('citr');
  await page.locator('#search-food').click();
  await page.getByRole('button', { name: 'Choisir Produit test citron', exact: true }).waitFor();
  if (calls !== 1) throw new Error('Local search made a remote call');
  await page.locator('#cancel-food').click();
  await page.locator('#add-food').click();
  await page.locator('#local-search').uncheck(); await page.locator('#food-query').fill('2000000000008');
  await page.locator('#search-food').click(); await page.getByRole('button', { name: 'Choisir Produit test citron', exact: true }).click();
  await page.locator('#portion-quantity').fill('250'); await page.locator('#portion-unit').selectOption('ml');
  if (await page.locator('#food-kcal').inputValue() !== '308.5') throw new Error('Volume portion wrong');
  await page.setViewportSize({ width: 1365, height: 1000 });
  await page.screenshot({ path: join(root, 'artifacts/nutrition-desktop.png'), fullPage: true });
  await page.locator('#manual-food').click(); await page.locator('#food-name').fill('Repas manuel test'); await page.locator('#food-kcal').fill('100');
  await page.locator('#save-food').click(); await page.locator('#food-dialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.getElementById('total').textContent === '254,3');
  offline = true;
  await page.locator('#add-food').click(); await page.locator('#food-query').fill('orange'); await page.locator('#search-food').click();
  await page.waitForFunction(() => document.getElementById('search-status').textContent.includes('indisponible'));
  await page.locator('#cancel-food').click();
  await page.locator('#add-food').click(); await page.locator('#food-query').fill('citron'); await page.locator('#search-food').click();
  await page.getByRole('button', { name: 'Choisir Produit test citron', exact: true }).waitFor();
  await page.locator('#cancel-food').click();
  await page.getByRole('button', { name: 'Modifier Produit test citron', exact: true }).click();
  await page.locator('#food-kcal').fill('200'); await page.locator('#save-food').click();
  await page.locator('#food-dialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.getElementById('total').textContent === '300');
  if (await page.locator('.entry-source').count()) throw new Error('Manual override still claims database source');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(JSON.stringify({ browser: 'Chromium', widths: [360, 1365], provider: 'simulated OFF', search: true,
    missingEnergyDisabled: true, unitConfirmation: true, calculation: true, snapshotAfterReload: true, sourceOnMealEdit: true,
    offlineLocalSearch: true, barcode: true, manualOverride: true, outageMessage: true, pageErrors: errors }));
} finally {
  await browser?.close();
  await new Promise(resolve => { server.closeAllConnections(); server.close(resolve); });
  await rm(directory, { recursive: true, force: true });
}
